import groovy.json.JsonOutput

def call() {

    def buildDir  = "builds/Build_${env.BUILD_NUMBER}"
    def reportDir = "${buildDir}/reports/eslint"

    sh "mkdir -p ${reportDir}"

    echo """
====================================
NODE VERSION
====================================
"""

    sh "node -v"

    echo """
====================================
NPM VERSION
====================================
"""

    sh "npm -v"

    echo """
====================================
INSTALLING DEPENDENCIES
====================================
"""

    sh "npm ci"

    echo """
====================================
RUNNING ESLINT
====================================
"""

    def eslintExitCode = sh(
        script: """
            export NODE_OPTIONS="--max-old-space-size=4096"

            npx eslint . \
                --ignore-pattern node_modules \
                --ignore-pattern .scannerwork \
                --ignore-pattern builds \
                --ignore-pattern dist \
                --ignore-pattern coverage \
                --format json \
                --output-file ${reportDir}/eslint-report.json
        """,
        returnStatus: true
    )

    echo "ESLint Exit Code : ${eslintExitCode}"

    if (!fileExists("${reportDir}/eslint-report.json")) {

        currentBuild.result = "FAILURE"

        error("""
====================================

ESLINT EXECUTION FAILED

Report file was not generated.

Expected:

${reportDir}/eslint-report.json

Common Causes:

- ESLint configuration error
- Node.js Out Of Memory
- Missing ESLint plugin
- Missing parser
- Invalid package installation

====================================
""")
    }

    def report = readJSON(
        file: "${reportDir}/eslint-report.json"
    )

    int errors = 0
    int warnings = 0

    report.each { file ->

        errors += file.errorCount ?: 0
        warnings += file.warningCount ?: 0
    }

    if (eslintExitCode != 0) {

        echo """
====================================
ESLINT FINDINGS (TOP RESULTS)
====================================
"""

        int displayedFiles = 0

        report.each { file ->

            if (displayedFiles >= 20) {
                return
            }

            if (file.messages?.size() > 0) {

                echo """
------------------------------------
FILE
${file.filePath}
------------------------------------
"""

                int displayedMessages = 0

                file.messages.each { msg ->

                    if (displayedMessages >= 10) {
                        return
                    }

                    echo """
Line      : ${msg.line ?: 'N/A'}
Column    : ${msg.column ?: 'N/A'}
Severity  : ${msg.severity == 2 ? 'ERROR' : 'WARNING'}
Rule      : ${msg.ruleId ?: 'N/A'}
Message   : ${msg.message ?: 'N/A'}
------------------------------------
"""

                    displayedMessages++
                }

                displayedFiles++
            }
        }

        echo """
====================================

ESLINT VALIDATION FAILED

Total Errors   : ${errors}
Total Warnings : ${warnings}

See full report:
${reportDir}/eslint-findings.txt

====================================
"""
    }

    def summary = [
        tool     : "ESLint",
        errors   : errors,
        warnings : warnings,
        status   : "SUCCESS"
    ]

    if (errors > 0) {

        summary.status = "APPROVAL_REQUIRED"

    } else if (warnings > 0) {

        summary.status = "WARNING"
    }

    def fullReport = new StringBuilder()

    fullReport << """
=========================================
ESLINT FINDINGS REPORT
=========================================

Generated By : Jenkins

Build Number : ${env.BUILD_NUMBER}

=========================================

"""

    report.each { file ->

        if (file.messages?.size() > 0) {

            fullReport << """

File:
${file.filePath}

-----------------------------------------

"""

            file.messages.eachWithIndex { msg, index ->

                fullReport << """

Finding #${index + 1}

Line      : ${msg.line ?: 'N/A'}

Column    : ${msg.column ?: 'N/A'}

Severity  : ${msg.severity == 2 ? 'ERROR' : 'WARNING'}

Rule      : ${msg.ruleId ?: 'N/A'}

Message   : ${msg.message ?: 'N/A'}

-----------------------------------------

"""
            }
        }
    }

    fullReport << """

=========================================
SUMMARY
=========================================

Errors   : ${errors}

Warnings : ${warnings}

Status   : ${summary.status}

ExitCode : ${eslintExitCode}

=========================================
"""

    writeFile(
        file: "${reportDir}/eslint-findings.txt",
        text: fullReport.toString()
    )

    writeFile(
        file: "${reportDir}/eslint-summary.json",
        text: JsonOutput.prettyPrint(
            JsonOutput.toJson(summary)
        )
    )

    archiveArtifacts(
        artifacts: "${reportDir}/**",
        fingerprint: true,
        allowEmptyArchive: true
    )

    currentBuild.description =
        (currentBuild.description ?: "") +
        " | ESLint[E=${errors},W=${warnings}]"

    echo """
=========================================

ESLINT SUMMARY

Errors      : ${errors}

Warnings    : ${warnings}

Status      : ${summary.status}

Exit Code   : ${eslintExitCode}

Reports

${reportDir}

=========================================
"""

    if (summary.status == "APPROVAL_REQUIRED") {

        error("""
====================================

ESLINT GATE FAILED

Errors Found : ${errors}
Warnings     : ${warnings}

The top ESLint findings were printed above.

Review and fix the violations before proceeding.

====================================
""")
    }

    return summary
}