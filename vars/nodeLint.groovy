import groovy.json.JsonOutput

def call() {

    def buildDir  = "builds/Build_${env.BUILD_NUMBER}"
    def reportDir = "${buildDir}/reports/eslint"

    if (!fileExists(buildDir)) {
        sh "mkdir -p ${buildDir}"
    }

    if (!fileExists(reportDir)) {
        sh "mkdir -p ${reportDir}"
    }

    sh """
        echo "===================================="
        echo "NODE VERSION"
        node -v

        echo "===================================="
        echo "NPM VERSION"
        npm -v

        echo "===================================="
        echo "INSTALLING DEPENDENCIES"

        npm ci

        echo "===================================="
        echo "RUNNING ESLINT"

        npx eslint . \
            --format json \
            --output-file ${reportDir}/eslint-report.json
    """

    def report = readJSON(
        file: "${reportDir}/eslint-report.json"
    )

    int errors = 0
    int warnings = 0

    report.each { file ->

        errors += file.errorCount ?: 0
        warnings += file.warningCount ?: 0
    }

    def summary = [
        tool     : "ESLint",
        errors   : errors,
        warnings : warnings,
        status   : "SUCCESS"
    ]

    if (errors > 0) {

        summary.status = "APPROVAL_REQUIRED"

    } else if (warnings > 0) {

        summary.status = "UNSTABLE"
    }

    def fullReport = new StringBuilder()

    fullReport << """
=========================================
ESLINT FINDINGS REPORT
=========================================

Generated By : Jenkins

Build Number : ${env.BUILD_NUMBER}

=========================================

"""

    report.each { file ->

        if (file.messages?.size() > 0) {

            fullReport << """

File:
${file.filePath}

-----------------------------------------

"""

            file.messages.eachWithIndex { msg, index ->

                fullReport << """

Finding #${index + 1}

Line      : ${msg.line ?: 'N/A'}

Column    : ${msg.column ?: 'N/A'}

Severity  : ${msg.severity == 2 ? 'ERROR' : 'WARNING'}

Rule      : ${msg.ruleId ?: 'N/A'}

Message   : ${msg.message ?: 'N/A'}

-----------------------------------------

"""
            }
        }
    }

    fullReport << """

=========================================
SUMMARY
=========================================

Errors   : ${errors}

Warnings : ${warnings}

Status   : ${summary.status}

=========================================
"""

    writeFile(
        file: "${reportDir}/eslint-findings.txt",
        text: fullReport.toString()
    )

    writeFile(
        file: "${reportDir}/eslint-summary.json",
        text: JsonOutput.prettyPrint(
            JsonOutput.toJson(summary)
        )
    )

    echo """
=========================================

ESLINT SUMMARY

Errors      : ${errors}

Warnings    : ${warnings}

Status      : ${summary.status}

Reports

${reportDir}

=========================================
"""

    sh """
        echo "===== GENERATED ESLINT FILES ====="
        ls -ltr ${reportDir}
    """

    archiveArtifacts(
        artifacts: "${reportDir}/**",
        fingerprint: true,
        allowEmptyArchive: false
    )

    currentBuild.description =
        (currentBuild.description ?: "") +
        " | ESLint[E=${errors},W=${warnings}]"

    if (warnings > 0) {

        currentBuild.result = 'UNSTABLE'
    }

    return summary
}